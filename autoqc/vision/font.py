def _parse(spec: str) -> dict[str, tuple[int, ...]]:
    font: dict[str, tuple[int, ...]] = {}
    blocks = [block.strip("\n") for block in spec.strip().split("\n\n")]
    for block in blocks:
        lines = block.split("\n")
        if len(lines) != 8:
            raise RuntimeError(f"glyph block must be 8 lines, got {len(lines)}: {lines[0]!r}")
        char = lines[0]
        if len(char) != 1:
            raise RuntimeError(f"glyph name must be one character: {char!r}")
        rows: list[int] = []
        for row in lines[1:]:
            if len(row) != GLYPH_W or any(bit not in "01" for bit in row):
                raise RuntimeError(f"bad row for {char!r}: {row!r}")
            rows.append(int(row, 2))
        glyph = tuple(rows)
        if not any(glyph):
            raise RuntimeError(f"blank glyph {char!r}")
        font[char] = glyph
    return font


FONT: dict[str, tuple[int, ...]] = _parse(_RAW)

_seen: dict[tuple[int, ...], str] = {}
for _char, _glyph in FONT.items():
    if _glyph in _seen:
        raise RuntimeError(f"glyph collision between {_seen[_glyph]!r} and {_char!r}")
    _seen[_glyph] = _char

GLYPH_INDEX: dict[tuple[int, ...], str] = {glyph: char for char, glyph in FONT.items()}


def text_width(text: str) -> int:
    return PITCH * len(text)


def draw_text(image, x: int, y: int, text: str, color: tuple[int, int, int]) -> int:
    """Draw ``text`` at the top-left of the cell. Unknown characters raise."""
    paint = (int(color[0]), int(color[1]), int(color[2]))
    height, width = image.shape[:2]
    cursor = x
    for char in text:
        if char != " ":
            rows = FONT.get(char)
            if rows is None:
                raise ValueError(f"unsupported glyph {char!r}")
            for row_index, bits in enumerate(rows):
                yy = y + row_index
                if yy < 0 or yy >= height:
                    continue
                for col_index in range(GLYPH_W):
                    if bits & (1 << (GLYPH_W - 1 - col_index)):
                        xx = cursor + col_index
                        if 0 <= xx < width:
                            image[yy, xx] = paint
        cursor += PITCH
    return cursor
